-- Windows regressions for small workflow improvements.
local folder=app.fs.joinPath(app.fs.filePath(app.fs.appPath),"data/extensions/minecraft-tools")
local core=dofile(app.fs.joinPath(folder,"minecraft_tools_core.lua"))
local sheet=dofile(app.fs.joinPath(folder,"minecraft_tools_sheet.lua"))
local exporter=dofile(app.fs.joinPath(folder,"minecraft_tools_export.lua"))
local function fails(fn) assert(not pcall(fn),"Expected invalid input rejection") end
local s=Sprite(128,64)
s.filename="atlas.aseprite"
s.gridBounds=Rectangle(0,0,12,12)
s.selection:select(Rectangle(16,0,32,64))
assert(sheet.cellSize(core,s)==16)
s.selection:select(Rectangle(16,0,32,32))
assert(sheet.cellSize(core,s)==16)
s.selection:select(Rectangle(32,32,32,32))
assert(sheet.cellSize(core,s)==32)
s.gridBounds=Rectangle(0,0,64,64)
assert(sheet.cellSize(core,s)==64,"A smaller selection must not override the document grid")
s.selection:deselect()
assert(sheet.rectangle(core,s,4,1,16,4,2)==Rectangle(64,16,64,32))
local x,y=sheet.step(core,s,4,2,16,4,2,1)
assert(x==0 and y==0,"Next multi-cell region must wrap at the end")
x,y=sheet.step(core,s,0,0,16,4,2,-1)
assert(x==4 and y==2,"Previous multi-cell region must wrap backwards")
local partial={width=144,height=80}
x,y=sheet.step(core,partial,0,0,16,4,2,-1);assert(x==4 and y==2)
x,y=sheet.step(core,partial,x,y,16,4,2,1);assert(x==0 and y==0)
x,y=sheet.step(core,partial,1,1,16,4,2,-1);assert(x==5 and y==3)
x,y=sheet.step(core,partial,x,y,16,4,2,1);assert(x==1 and y==1)
fails(function() sheet.rectangle(core,s,0,0,16,0,1) end)
fails(function() sheet.rectangle(core,s,-1,0,16,1,1) end)
fails(function() sheet.rectangle(core,s,0,0,16,1.5,1) end)
fails(function() sheet.rectangle(core,s,0,0,16,0/0,1) end)
fails(function() sheet.rectangle(core,s,7,3,16,2,2) end)
local bounds=Rectangle(16,0,16,16)
assert(core.assetName(s,bounds)=="r001_c002")
sheet.nameCell(core,s,bounds,"tools/copper_sword")
assert(#s.slices==1 and core.assetName(s,bounds)=="tools/copper_sword")
sheet.nameCell(core,s,bounds,"tools/bronze_sword")
assert(#s.slices==1 and s.slices[1].name=="tools/bronze_sword")
fails(function() sheet.nameCell(core,s,Rectangle(32,0,16,16),"tools/bronze_sword") end)
assert(#s.slices==1,"A rejected duplicate must not create another slice")
s.selection:select(Rectangle(0,0,16,16));s.selection:subtract(Rectangle(0,0,1,1))
local source=Image(16,16)
local red=Color{r=220,g=40,b=30}.rgbaPixel
source:putPixel(0,0,red)
source:putPixel(1,0,red)
local transformed=sheet.transform(sheet.mask(s,Rectangle(0,0,16,16),source),"Rotate clockwise")
assert(transformed:getPixel(15,0)==0,"Rotation must not import pixels from selection holes")
assert(transformed:getPixel(15,1)==red)
local before=Image(s.cels[1].image)
sheet.replace(s,Rectangle(0,0,16,16),transformed,"Cell test")
assert(s.cels[1].image:getPixel(15,1)==red)
app.undo();assert(s.cels[1].image:isEqual(before))
local hidden=Image(2,2)
hidden:putPixel(0,0,app.pixelColor.rgba(255,0,0,0))
hidden:putPixel(1,1,app.pixelColor.rgba(0,0,255,0))
local report=core.seams(hidden)
assert(report.edgeDifferences==0 and report.colors==0 and report.partial==0)
hidden:putPixel(0,0,app.pixelColor.rgba(12,34,56,100))
report=core.seams(hidden)
assert(report.colors==1 and report.partial==1 and report.transparent==4)
local ramp=core.ramp(Color{h=350,s=1,v=1,a=100},Color{h=10,s=1,v=1,a=200},3,true)
assert(ramp[2].red>250 and ramp[2].green<5 and ramp[2].blue<5,"HSV must take the short path across hue zero")
assert(ramp[2].alpha==150)
local height=Image(3,3)
for p in height:pixels() do p(app.pixelColor.rgba(p.y*80,p.y*80,p.y*80,255)) end
local positive=core.normalMap(height,4,true)
local negative=core.normalMap(height,4,true,true)
local a,b=positive:getPixel(1,1),negative:getPixel(1,1)
assert(app.pixelColor.rgbaR(a)==app.pixelColor.rgbaR(b) and app.pixelColor.rgbaB(a)==app.pixelColor.rgbaB(b))
assert(app.pixelColor.rgbaG(a)<128 and app.pixelColor.rgbaG(b)>128)
s:close()
local cell=Sprite(16,16)
local root=app.fs.joinPath(app.fs.tempPath,"minecraft-qol-" .. os.time())
local path=app.fs.joinPath(root,"assets","test","textures","item","tool.png.mcmeta")
assert(app.fs.makeAllDirectories(app.fs.filePath(path)))
local function write(text) local f=assert(io.open(path,"wb"));assert(f:write(text));assert(f:close()) end
local opts={root=root,namespace="test",path="tool",kind="Weapon / tool",models=false,animate=false}
write('{"texture":{"blur":false},"gui":{"scaling":{"type":"stretch"}},"custom":{"values":[1,2,3]}}')
assert(#exporter.plan(core,cell,opts)==1,"Static export should retain valid non-animation metadata")
cell:newEmptyFrame();opts.animate=true;opts.interpolate=true
local files=exporter.plan(core,cell,opts)
local meta=json.decode(files[2].text)
assert(meta.texture.blur==false and meta.gui.scaling.type=="stretch")
assert(meta.custom.values[1]==1 and meta.custom.values[3]==3)
assert(meta.animation.interpolate==true and #meta.animation.frames==2)
exporter.write(files,true)
opts.animate=false
fails(function() exporter.plan(core,cell,opts) end)
write('')
fails(function() exporter.plan(core,cell,opts) end)
write('not-json')
fails(function() exporter.plan(core,cell,opts) end)
write('[]')
fails(function() exporter.plan(core,cell,opts) end)
write('\239\187\191{"texture":{"clamp":true}}')
assert(#exporter.plan(core,cell,opts)==1,"UTF-8 BOM metadata is accepted")
cell:close()
print("Navigator bounds/wrap, slice names, masked rotation, palette/seams, HSV, normals and metadata preservation passed")
