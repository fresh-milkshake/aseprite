local root=app.fs.joinPath(app.fs.filePath(app.fs.appPath),"data/extensions/minecraft-tools")
local preview=dofile(app.fs.joinPath(root,"minecraft_tools_preview.lua"))
local sheet=dofile(app.fs.joinPath(root,"minecraft_tools_sheet.lua"))
local s=Sprite(16,16)
local before=Image(16,16)
local red=Color{r=220,g=30,b=20}.rgbaPixel
before:putPixel(0,0,red)
s.selection:select(Rectangle(0,0,16,16));s.selection:subtract(Rectangle(0,0,1,1))
local result=Image(16,16);result:putPixel(2,2,red)
local display=sheet.displayEdit(s,Rectangle(0,0,16,16),before,result)
assert(display:getPixel(0,0)==red and display:getPixel(2,2)==red)
local compare=preview.compare(before,display)
assert(compare.width==40 and compare.height==16)
assert(compare:getPixel(0,0)==red and compare:getPixel(24,0)==red)
assert(before:getPixel(2,2)==0,"Comparison cannot modify source pixels")
s:close()
