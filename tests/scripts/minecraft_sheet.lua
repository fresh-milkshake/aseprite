-- Atlas regressions, executed only by the Windows CLI suite.
local folder=app.fs.joinPath(app.fs.filePath(app.fs.appPath),"data/extensions/minecraft-tools")
local core=dofile(app.fs.joinPath(folder,"minecraft_tools_core.lua"))
local sheet=dofile(app.fs.joinPath(folder,"minecraft_tools_sheet.lua"))
local exporter=dofile(app.fs.joinPath(folder,"minecraft_tools_export.lua"))
local armor=dofile(app.fs.joinPath(folder,"minecraft_tools_armor.lua"))
local function fails(fn) assert(not pcall(fn),"Expected rejection") end
local s=Sprite(64,64,ColorMode.RGB)
local red=app.pixelColor.rgba(220,40,30,128)
local blue=app.pixelColor.rgba(20,40,220,255)
local hidden=app.pixelColor.rgba(12,34,56,0)
s.cels[1].image:putPixel(16,0,red)
s.cels[1].image:putPixel(0,0,blue)
s.cels[1].image:putPixel(63,63,hidden)
fails(function() core.cell(s) end) -- Never accidentally export an entire atlas.
s.selection:select(Rectangle(16,0,16,16))
assert(core.cell(s)==Rectangle(16,0,16,16))
local captured=core.capture(s,1,core.cell(s))
assert(captured.width==16 and captured:getPixel(0,0)==red)
local before=Image(s.cels[1].image)
sheet.replace(s,core.cell(s),sheet.transform(captured,"Rotate clockwise"),"Test cell transform")
assert(s.cels[1].image:getPixel(31,0)==red)
assert(s.cels[1].image:getPixel(0,0)==blue)
assert(s.cels[1].image:getPixel(63,63)==hidden)
app.undo();assert(s.cels[1].image:isEqual(before));app.redo();app.undo()
local cleaned=sheet.alpha(captured,129)
assert(app.pixelColor.rgbaA(cleaned:getPixel(0,0))==0)
assert(app.pixelColor.rgbaR(cleaned:getPixel(0,0))==220)
local raised=sheet.alpha(captured,128)
assert(app.pixelColor.rgbaA(raised:getPixel(0,0))==255)
local outline=sheet.outline(captured,Color{r=1,g=2,b=3},false,false)
assert(app.pixelColor.rgbaA(outline:getPixel(0,0))==0)
assert(app.pixelColor.rgbaA(outline:getPixel(1,0))==255)
assert(outline:getPixel(1,1)==0)
local inside=sheet.outline(captured,Color{r=1,g=2,b=3},true,false)
assert(app.pixelColor.rgbaA(inside:getPixel(0,0))==255)
local free=sheet.space(core.capture(s,1),16,3)
assert(free==Rectangle(0,16,48,16),"Variants must avoid existing cells")
assert(sheet.hue(captured,0,0,0,false):isEqual(captured),"Neutral hue settings must preserve exact color/alpha")
local hue=sheet.hue(captured,120,0,0,false)
assert(app.pixelColor.rgbaA(hue:getPixel(0,0))==128)
assert(app.pixelColor.rgbaG(hue:getPixel(0,0))>150)
assert(hue:getPixel(5,5)==0)
local neutral=Image(1,1);neutral:putPixel(0,0,Color{r=128,g=128,b=128}.rgbaPixel)
assert(sheet.hue(neutral,120,30,30,true):isEqual(neutral))
local slice=s:newSlice(Rectangle(16,0,16,16));slice.name="tools/red_sword"
local root=app.fs.joinPath(app.fs.tempPath,"mc-sheet-" .. os.time())
local opts={root=root,namespace="atlas",prefix="",size="16",skip=true,kind="Weapon / tool",models=true,modern=true,animate=false}
local files,manifest=sheet.plan(core,exporter,s,opts)
assert(#manifest==2 and #files==6,"Only two occupied cells should export")
assert(manifest[2].asset=="atlas:tools/red_sword")
assert(files[4].image.width==16 and files[4].image:getPixel(0,0)==red)
assert(exporter.write(files,false)==6)
assert(Image{fromFile=files[4].path}:isEqual(files[4].image))
assert(s.cels[1].image:isEqual(before),"Export must not alter source")
-- A repeated native slice name must be rejected before overwriting anything.
local duplicate=s:newSlice(Rectangle(0,0,16,16));duplicate.name=slice.name
fails(function() sheet.plan(core,exporter,s,opts) end)
s:deleteSlice(duplicate)
opts.size="32";opts.bounds=Rectangle(0,0,32,32);opts.models=false
local effects=sheet.plan(core,exporter,s,opts)
assert(#effects==1 and effects[1].image.width==32)
for _,size in ipairs({64,128}) do
  local large=Sprite(size*2,size)
  large.gridBounds=Rectangle(0,0,size,size)
  large.cels[1].image:putPixel(0,0,red)
  large.cels[1].image:putPixel(size,0,blue)
  local grid=sheet.cellSize(core,large)
  local largeFiles,largeManifest=sheet.plan(core,exporter,large,{
    root=root,namespace="atlas",prefix=tostring(size),kind="Block",size=grid,skip=true })
  assert(grid==size and #largeManifest==2 and #largeFiles==2)
  assert(exporter.write(largeFiles,false)==2)
  local first=Image{fromFile=largeFiles[1].path}
  local second=Image{fromFile=largeFiles[2].path}
  assert(first.width==size and second.width==size and first.height==size and second.height==size)
  assert(first:getPixel(0,0)==red and second:getPixel(0,0)==blue)
  large:close()
end
opts.bounds=Rectangle(16,0,32,32)
fails(function() sheet.plan(core,exporter,s,opts) end)
-- Cell timeline remains spatially aligned, with exact Java tick durations.
s:newEmptyFrame();s.frames[1].duration=.1;s.frames[2].duration=.15
local f2=Image(64,64);f2:putPixel(17,1,blue)
local second=s:newCel(s.layers[1],2,f2,Point(0,0))
opts.bounds=Rectangle(16,0,16,16);opts.size="16";opts.animate=true
local anim,anames=sheet.plan(core,exporter,s,opts)
assert(#anames==1 and anim[1].image.width==16 and anim[1].image.height==32)
assert(anim[1].image:getPixel(0,0)==red and anim[1].image:getPixel(1,17)==blue)
local metadata=json.decode(anim[2].text)
assert(metadata.animation.frames[2].time==3)
second.image:putPixel(33,1,blue)
opts.bounds=Rectangle(32,0,16,16)
local delayed,delayedNames=sheet.plan(core,exporter,s,opts)
assert(#delayedNames==1 and delayed[1].image:getPixel(1,17)==blue,"Cells appearing after frame 1 must export")
s.frames[2].duration=.075
fails(function() sheet.plan(core,exporter,s,opts) end)
-- Armor can occupy two named rectangles inside the same static atlas.
local atlas=Sprite(128,64)
local armorRed=app.pixelColor.rgba(220,40,30,255)
atlas.cels[1].image:putPixel(8,8,blue)
atlas.cels[1].image:putPixel(68,20,armorRed)
local upper={sprite=atlas,bounds=Rectangle(0,0,64,32)}
local legs={sprite=atlas,bounds=Rectangle(64,0,64,32)}
assert(armor.atlas(core,upper):getPixel(8,8)==blue)
assert(armor.atlas(core,legs):getPixel(4,20)==armorRed)
local doll=armor.paperdoll(armor.atlas(core,upper),armor.atlas(core,legs))
assert(doll:getPixel(8,4)==blue and doll:getPixel(8,24)==armorRed)
local equipment=armor.plan(core,upper,legs,nil,{root=root,namespace="atlas",path="armor",profile="Equipment (1.21.4-1.21.11)"})
assert(#equipment==3 and equipment[1].image.width==64)
atlas:close();s:close()
local indexed=Sprite(16,16,ColorMode.INDEXED)
local rgb=Image(1,1,ColorMode.RGB);rgb:putPixel(0,0,red)
local converted=sheet.hue(rgb,120,0,0,false)
assert(app.pixelColor.rgbaG(converted:getPixel(0,0))>150,
  "Merged RGB capture must stay RGB when the active document is indexed")
indexed:close()
print("Sheet cells, transforms, alpha, outlines, hue, batch export, effects, animations and embedded armor passed")
