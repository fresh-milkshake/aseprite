-- Exercise the actual registered command and document undo history.
local s = Sprite(4,4,ColorMode.RGB)
local red = app.pixelColor.rgba(240,30,25,128)
local outside = app.pixelColor.rgba(30,25,240,255)
local hidden = app.pixelColor.rgba(17,99,205,0)
local image = Image(6,4,ColorMode.RGB)
image:putPixel(0,0,outside)
image:putPixel(1,0,red)
image:putPixel(5,3,hidden)
s.cels[1].image=image
s.cels[1].position=Point(-1,0)
local before=Image(s.cels[1].image)
app.command.MinecraftOffset()
assert(s.cels[1].position == Point(-1,0))
assert(s.cels[1].image:getPixel(3,2) == red, "Wrapped pixel must move without doubling alpha")
assert(s.cels[1].image:getPixel(0,0) == outside, "Off-canvas artwork must survive")
assert(s.cels[1].image:getPixel(5,3) == hidden, "Transparent pixels must preserve their RGB data")
app.undo()
assert(s.cels[1].image:isEqual(before),"One Undo must restore the complete cel")
assert(s.cels[1].position == Point(-1,0))
app.redo()
assert(s.cels[1].image:getPixel(3,2) == red)
app.undo()
s.selection:select(Rectangle(0,0,2,2))
s.selection:subtract(Rectangle(1,0,1,1))
s.cels[1].image:putPixel(2,0,outside)
local maskedBefore = Image(s.cels[1].image)
local unchanged = s.cels[1].image:getPixel(2,0)
app.command.MinecraftOffset()
assert(s.cels[1].image:getPixel(2,0) == unchanged,"Selection holes must remain unchanged")
assert(s.cels[1].image:getPixel(1,1) == 0,"Unselected source pixels must not be copied into the selection")
app.undo()
assert(s.cels[1].image:isEqual(maskedBefore))
s:close()
